const fs = require('node:fs');
const assert = require('node:assert/strict');
const { chromium } = require('playwright');
const { launchOptions } = require('./helpers.cjs');
const source = fs.readFileSync(`${__dirname}/../src/settings-module.js`, 'utf8');
(async () => {
  const browser = await chromium.launch(launchOptions());
  const context = await browser.newContext({ viewport:{ width:1280,height:900 } });
  const page = await context.newPage();
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  try {
    await page.route('**/*', route => route.fulfill({ body:'<!doctype html><html><head><style>body{margin:0;background:black;color:white}article{width:100%;box-sizing:border-box;padding:12px;font-size:17px;line-height:1.4}.xt6-media{max-height:var(--xt6-media-height,360px);overflow:auto}</style></head><body><article data-testid="tweet"><div data-testid="tweetText">A post with enough words to check its reading preferences.</div><div class="xt6-media" style="height:600px">Media</div></article></body></html>', contentType:'text/html' }));
    await page.goto('https://x.com/home');
    await page.addScriptTag({ content:`(() => {${source}\ninitReadingSettings();window.__settingsTest={readingSettings,initReadingSettings,syncReadingSettings,normalizeReadingSettings};})();` });
    await page.getByRole('button', { name:'Reading settings',exact:true }).click();
    assert.equal(await page.locator('#xt6-settings-dialog').evaluate(d => d.open), true);
    assert.equal(await page.locator('#xt6-settings-dialog').getAttribute('data-theme'), 'dark');
    assert.equal(await page.locator('article').evaluate(el => el.getBoundingClientRect().width), 1280);
    await page.locator('#xt6-setting-fontSize').selectOption('20');
    await page.locator('#xt6-setting-lineHeight').selectOption('1.6');
    await page.locator('#xt6-setting-postSpacing').selectOption('compact');
    await page.locator('#xt6-setting-mediaHeight').fill('480');
    await page.locator('#xt6-setting-autoExpand').check();
    assert.equal(await page.locator('[data-testid="tweetText"]').evaluate(el => getComputedStyle(el).fontSize), '20px');
    assert.equal(await page.locator('[data-testid="tweetText"]').evaluate(el => getComputedStyle(el).lineHeight), '32px');
    assert.equal(await page.locator('article').evaluate(el => getComputedStyle(el).paddingTop), '6px');
    assert.equal(await page.locator('.xt6-media').evaluate(el => getComputedStyle(el).maxHeight), '480px');
    assert.equal(await page.locator('article').evaluate(el => el.getBoundingClientRect().width), 1280);
    const saved = await page.evaluate(() => JSON.parse(localStorage.getItem('xt6-reading-settings-v1')));
    assert.deepEqual(saved, { fontSize:20,lineHeight:1.6,postSpacing:'compact',mediaHeight:480,autoExpand:true });
    await page.getByRole('button', { name:'Done',exact:true }).click();
    assert.equal(await page.locator('#xt6-settings-dialog').evaluate(d => d.open), false);
    assert.equal(await page.evaluate(() => document.activeElement.id), 'xt6-settings-launcher');
    await page.evaluate(() => { window.__settingsTest.initReadingSettings();window.__settingsTest.syncReadingSettings(); });
    assert.equal(await page.locator('#xt6-settings-launcher').count(), 1);
    await page.getByRole('button', { name:'Reading settings',exact:true }).click();
    await page.getByRole('button', { name:'Reset defaults',exact:true }).click();
    assert.equal(await page.locator('[data-testid="tweetText"]').evaluate(el => getComputedStyle(el).fontSize), '17px');
    assert.equal(await page.locator('article').evaluate(el => getComputedStyle(el).paddingTop), '12px');
    assert.equal(await page.locator('.xt6-media').evaluate(el => getComputedStyle(el).maxHeight), '360px');
    assert.equal(await page.locator('#xt6-setting-autoExpand').isChecked(), false);
    assert.equal(await page.locator('article').evaluate(el => el.getBoundingClientRect().width), 1280);
    const bad = await page.evaluate(() => window.__settingsTest.normalizeReadingSettings({fontSize:200,lineHeight:100,postSpacing:'bad',mediaHeight:Infinity,autoExpand:'true'}));
    assert.deepEqual(bad, { fontSize:0,lineHeight:0,postSpacing:'default',mediaHeight:360,autoExpand:false });
    assert.deepEqual(errors, []);
    console.log('PASS settings: live controls, local persistence, reset, validation, full-width preservation, focus return, no duplicates.');
  } finally { await context.close(); await browser.close(); }
})().catch(error => { console.error(error.stack);process.exitCode=1; });
